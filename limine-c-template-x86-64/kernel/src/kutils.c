bool lshift_status = 0;

bool is_lshift(uint8_t scancode) {//may be a better idea to remove get_key() from here and just pass in the key directly idk
    uint8_t shift_pressed = 0x2a;
    uint8_t shift_released = 0xaa;
    if (scancode == shift_released) {//state != shift_pressed || 
        lshift_status = 0;
        return 0;
    }
    else if (scancode == shift_pressed) {//state != shift_released || 
        lshift_status = 1;
        return 1;
    }
}

